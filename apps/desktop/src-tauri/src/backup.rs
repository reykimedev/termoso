//! Portable data: hosts as Termius-style CSV and whole vaults as a
//! password-protected `.labterm` backup (format in `labterm_client::backup`,
//! shared with the mobile apps).
//!
//! Both leave the webview out of the loop: the frontend only passes a target
//! path (chosen through the native dialog) and, for backups, a password. The
//! plaintext never crosses IPC.

use labterm_client::backup;
use labterm_core::model::{Entity, Identity};
use labterm_core::store::Store;
use serde::Serialize;
use uuid::Uuid;

use crate::error::{DesktopError, Result};
use crate::hosts;

// ───────────────────────────── CSV ─────────────────────────────

/// Column order of the exported CSV; the same header the importer accepts, so
/// a file exported here re-imports without mapping.
pub const CSV_HEADER: [&str; 8] = [
    "Groups",
    "Label",
    "Tags",
    "Hostname/IP",
    "Protocol",
    "Port",
    "Username",
    "Password",
];

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CsvExportReport {
    pub hosts: usize,
    /// True when the file contains plaintext passwords.
    pub passwords_included: bool,
    pub path: String,
}

fn csv_field(s: &str) -> String {
    if s.is_empty() {
        return String::new();
    }
    // Leading formula characters are neutralised so the file is safe to open
    // in a spreadsheet.
    let needs_prefix = matches!(s.chars().next(), Some('=' | '+' | '-' | '@'));
    let body = if needs_prefix {
        format!("'{s}")
    } else {
        s.to_string()
    };
    if body.contains(['"', ',', ';', '\n', '\r']) || body != body.trim() {
        format!("\"{}\"", body.replace('"', "\"\""))
    } else {
        body
    }
}

/// Render the hosts of `vault_id` (or every unlocked vault) as CSV.
///
/// Field mapping: `Groups` = group path joined with `/`, `Label`, `Tags`
/// (comma separated), `Hostname/IP`, `Protocol` (`ssh` or `telnet`), `Port`
/// and `Username` are the effective values shown on the host card.
/// `Password` is written only when `include_passwords` is set and the host's
/// own or inherited identity carries one; keys, certificates, proxies and
/// jump chains are never exported.
pub fn hosts_csv(
    store: &Store,
    vault_id: Option<Uuid>,
    include_passwords: bool,
) -> Result<(String, usize)> {
    if let Some(v) = vault_id
        && labterm_core::policy::export_denied(store, v)
    {
        return Err(DesktopError::invalid(
            labterm_core::policy::Denied::Export.message(),
        ));
    }
    let mut cards = hosts::cards(store, vault_id)?;
    cards.retain(|c| !labterm_core::policy::export_denied(store, c.vault_id));
    let mut out = String::new();
    out.push_str(&CSV_HEADER.join(","));
    out.push('\n');
    for c in &cards {
        let password = if include_passwords {
            let r = store.resolve_host_in(c.id, Some(c.vault_id))?;
            r.identity
                .as_ref()
                .and_then(|i: &Entity<Identity>| i.data.password.clone())
                .unwrap_or_default()
        } else {
            String::new()
        };
        let row = [
            csv_field(&c.group_path.join("/")),
            csv_field(&c.label),
            csv_field(&c.tags.join(", ")),
            csv_field(&c.address),
            csv_field(&c.protocol),
            csv_field(&c.port.to_string()),
            csv_field(&c.username),
            csv_field(&password),
        ];
        out.push_str(&row.join(","));
        out.push('\n');
    }
    Ok((out, cards.len()))
}

/// Slug usable as an `ssh_config` `Host` alias.
fn alias(label: &str) -> String {
    let mut out = String::new();
    for c in label.trim().chars() {
        if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('-') {
            out.push('-');
        }
    }
    let out = out.trim_matches('-').to_string();
    if out.is_empty() { "host".into() } else { out }
}

/// Hosts as an OpenSSH `ssh_config` fragment: one `Host` block per SSH host
/// with HostName / Port / User and `ProxyJump` through the stored jump chain.
/// Secrets never leave the vault (no IdentityFile, no passwords).
pub fn hosts_ssh_config(store: &Store, vault_id: Option<Uuid>) -> Result<(String, usize)> {
    if let Some(v) = vault_id
        && labterm_core::policy::export_denied(store, v)
    {
        return Err(DesktopError::invalid(
            labterm_core::policy::Denied::Export.message(),
        ));
    }
    let mut cards = hosts::cards(store, vault_id)?;
    cards
        .retain(|c| !labterm_core::policy::export_denied(store, c.vault_id) && c.protocol == "ssh");
    let mut used = std::collections::HashSet::new();
    let mut out = String::from("# Generated by Labterm — hosts only, no secrets.\n");
    for c in &cards {
        let mut a = alias(&c.label);
        let base = a.clone();
        let mut n = 2;
        while !used.insert(a.clone()) {
            a = format!("{base}-{n}");
            n += 1;
        }
        out.push_str(&format!("\nHost {a}\n    HostName {}\n", c.address));
        if c.port != 22 {
            out.push_str(&format!("    Port {}\n", c.port));
        }
        if !c.username.is_empty() {
            out.push_str(&format!("    User {}\n", c.username));
        }
        if let Ok(r) = store.resolve_host_in(c.id, Some(c.vault_id))
            && !r.chain.is_empty()
        {
            let jumps: Vec<String> = r.chain.iter().map(|h| alias(&h.data.label)).collect();
            out.push_str(&format!("    ProxyJump {}\n", jumps.join(",")));
        }
        if !c.group_path.is_empty() {
            out.push_str(&format!("    # group: {}\n", c.group_path.join("/")));
        }
    }
    Ok((out, cards.len()))
}

/// Hosts as an Ansible INI inventory: a group per folder (`a/b` → `[a_b]`)
/// and per tag, `ansible_host` / `ansible_port` / `ansible_user` per host.
pub fn hosts_ansible(store: &Store, vault_id: Option<Uuid>) -> Result<(String, usize)> {
    if let Some(v) = vault_id
        && labterm_core::policy::export_denied(store, v)
    {
        return Err(DesktopError::invalid(
            labterm_core::policy::Denied::Export.message(),
        ));
    }
    let mut cards = hosts::cards(store, vault_id)?;
    cards
        .retain(|c| !labterm_core::policy::export_denied(store, c.vault_id) && c.protocol == "ssh");
    let group = |s: &str| alias(s).replace(['-', '.'], "_");
    let mut groups: std::collections::BTreeMap<String, Vec<String>> = Default::default();
    let mut out = String::from("# Generated by Labterm — hosts only, no secrets.\n");
    let mut used = std::collections::HashSet::new();
    for c in &cards {
        let mut a = alias(&c.label);
        let base = a.clone();
        let mut n = 2;
        while !used.insert(a.clone()) {
            a = format!("{base}-{n}");
            n += 1;
        }
        let mut line = format!("{a} ansible_host={}", c.address);
        if c.port != 22 {
            line.push_str(&format!(" ansible_port={}", c.port));
        }
        if !c.username.is_empty() {
            line.push_str(&format!(" ansible_user={}", c.username));
        }
        out.push_str(&line);
        out.push('\n');
        if !c.group_path.is_empty() {
            groups
                .entry(group(&c.group_path.join("_")))
                .or_default()
                .push(a.clone());
        }
        for t in &c.tags {
            groups
                .entry(format!("tag_{}", group(t)))
                .or_default()
                .push(a.clone());
        }
    }
    for (g, members) in groups {
        out.push_str(&format!("\n[{g}]\n"));
        for m in members {
            out.push_str(&m);
            out.push('\n');
        }
    }
    Ok((out, cards.len()))
}

/// Write an `ssh_config` or Ansible inventory export to `path` (owner-only on Unix).
pub fn export_hosts_as(
    store: &Store,
    vault_id: Option<Uuid>,
    format: &str,
    path: &str,
) -> Result<CsvExportReport> {
    let (text, hosts) = match format {
        "ssh_config" => hosts_ssh_config(store, vault_id)?,
        "ansible" => hosts_ansible(store, vault_id)?,
        other => {
            return Err(DesktopError::invalid(format!(
                "unknown export format {other}"
            )));
        }
    };
    write_private(path, text.as_bytes())?;
    Ok(CsvExportReport {
        hosts,
        passwords_included: false,
        path: path.to_string(),
    })
}

/// Write the CSV to `path` (owner-only on Unix).
pub fn export_hosts_csv(
    store: &Store,
    vault_id: Option<Uuid>,
    include_passwords: bool,
    path: &str,
) -> Result<CsvExportReport> {
    let (text, hosts) = hosts_csv(store, vault_id, include_passwords)?;
    write_private(path, text.as_bytes())?;
    Ok(CsvExportReport {
        hosts,
        passwords_included: include_passwords,
        path: path.to_string(),
    })
}

fn write_private(path: &str, bytes: &[u8]) -> Result<()> {
    #[cfg(unix)]
    {
        use std::io::Write;
        use std::os::unix::fs::OpenOptionsExt;
        let mut f = std::fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(0o600)
            .open(path)?;
        f.write_all(bytes)?;
        f.flush()?;
        Ok(())
    }
    #[cfg(not(unix))]
    {
        std::fs::write(path, bytes)?;
        Ok(())
    }
}

