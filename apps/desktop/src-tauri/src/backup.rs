/// A backup's contents, plus where the file is.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BackupSummary {
    #[serde(flatten)]
    pub summary: backup::Summary,
    pub path: Option<String>,
}

/// Write an encrypted backup of `vault_ids` (every unlocked vault when empty)
/// to `path`; `keep_open` also keeps it open for `apply`.
pub fn export_file(
    store: &Store,
    vault_ids: &[Uuid],
    password: &str,
    path: &str,
    keep_open: bool,
) -> Result<BackupSummary> {
    let (bytes, summary) = backup::export(store, vault_ids, password, keep_open)?;
    write_private(path, &bytes)?;
    Ok(BackupSummary {
        summary,
        path: Some(path.to_string()),
    })
}

/// Decrypt a backup and keep it in memory for following `apply` calls.
pub fn inspect_file(path: &str, password: &str) -> Result<BackupSummary> {
    let meta = std::fs::metadata(path)?;
    if meta.len() > backup::MAX_FILE {
        return Err(DesktopError::invalid("backup file is too large"));
    }
    let bytes = std::fs::read(path)?;
    Ok(BackupSummary {
        summary: backup::inspect(&bytes, password)?,
        path: Some(path.to_string()),
    })
}

pub fn discard(preview_id: Uuid) {
    backup::discard(preview_id)
}

pub use backup::RestoreReport;

/// Restore the vault at index `source` of an inspected backup into
/// `target_vault_id`; see [`backup::restore`].
pub fn apply(
    store: &Store,
    preview_id: Uuid,
    source: usize,
    target_vault_id: Uuid,
) -> Result<RestoreReport> {
    backup::restore(store, preview_id, source, target_vault_id)
}

#[cfg(test)]
mod tests {
    use super::*;
    use labterm_core::model::{Group, Host, SshConfig};
    use labterm_crypto::keys::SymmetricKey;

    fn store() -> (Store, Uuid) {
        let s = Store::open_in_memory(SymmetricKey::generate()).expect("store");
        let v = s.local_vault().unwrap().id;
        (s, v)
    }

    fn seed(s: &Store, v: Uuid) -> Uuid {
        let group = s
            .insert(
                v,
                &Group {
                    label: "Prod, EU".into(),
                    ..Default::default()
                },
            )
            .unwrap();
        let identity = s
            .insert(
                v,
                &Identity {
                    label: "deploy".into(),
                    username: "deploy".into(),
                    password: Some("s3cret".into()),
                    ..Default::default()
                },
            )
            .unwrap();
        let ssh = s
            .insert(
                v,
                &SshConfig {
                    port: Some(2222),
                    identity_id: Some(identity),
                    ..Default::default()
                },
            )
            .unwrap();
        s.insert(
            v,
            &Host {
                label: "=web \"1\"".into(),
                address: "web1.example.com".into(),
                group_id: Some(group),
                ssh_config_id: Some(ssh),
                ..Default::default()
            },
        )
        .unwrap()
    }

    #[test]
    fn csv_omits_passwords_by_default_and_escapes() {
        let (s, v) = store();
        seed(&s, v);
        let (csv, n) = hosts_csv(&s, Some(v), false).unwrap();
        assert_eq!(n, 1);
        let mut lines = csv.lines();
        assert_eq!(lines.next().unwrap(), CSV_HEADER.join(","));
        let row = lines.next().unwrap();
        assert_eq!(
            row,
            "\"Prod, EU\",\"'=web \"\"1\"\"\",,web1.example.com,ssh,2222,deploy,"
        );
        assert!(!csv.contains("s3cret"));
        let (with, _) = hosts_csv(&s, Some(v), true).unwrap();
        assert!(with.lines().nth(1).unwrap().ends_with(",deploy,s3cret"));
    }

    #[test]
    fn csv_round_trips_through_importer() {
        let (s, v) = store();
        seed(&s, v);
        let (csv, _) = hosts_csv(&s, Some(v), false).unwrap();
        let preview = crate::import::parse_csv_text(&csv).unwrap();
        assert_eq!(preview.hosts.len(), 1);
        let h = &preview.hosts[0];
        assert_eq!(h.address, "web1.example.com");
        assert_eq!(h.port, Some(2222));
        assert_eq!(h.username, "deploy");
        assert_eq!(h.group_path, vec!["Prod, EU".to_string()]);
        assert!(h.password.is_none());
    }
}
